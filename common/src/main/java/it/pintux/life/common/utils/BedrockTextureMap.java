/**
 * Java Material name -> Bedrock resource-pack texture path.
 *
 * <p>Generated from Mojang's vanilla atlases (bedrock-samples: resource_pack/textures/
 * item_texture.json + terrain_texture.json). Bedrock kept the legacy texture names, which often
 * differ from the modern Java material name - noun-first ordering (COOKED_CHICKEN ->
 * chicken_cooked, GOLDEN_APPLE -> apple_golden), older words (GOLDEN_SWORD -> gold_sword,
 * LIGHT_GRAY_DYE -> dye_powder_silver, TERRACOTTA -> hardened_clay), moved folders (spawn eggs),
 * and variants that reuse another block's texture (OAK_STAIRS -> planks_oak, waxed copper ->
 * the unwaxed texture). It also corrects materials filed under textures/items that only exist
 * under textures/blocks.
 *
 * <p>Every entry here is a material whose plain lowercase guess does NOT exist in the atlases, so
 * consulting this table first can only replace a broken texture, never a working one. Materials
 * absent from the table keep {@link IconResolver}'s original behaviour.
 */
